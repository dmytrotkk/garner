export type Suggestion<Item> = { category: Item; why: string }

export const suggest = <Item extends { icon: CategoryIcon }>(
  party: string,
  categories: readonly Item[],
): Suggestion<Item>[] => {
  const text = ` ${party} `
  return categories
    .flatMap((category) => {
      const [why] = keywords[category.icon]
        .filter((word) => text.includes(` ${word}`))
        .sort((a, b) => b.length - a.length)
      return why ? [{ category, why }] : []
    })
    .sort((a, b) => b.why.length - a.why.length)
}
